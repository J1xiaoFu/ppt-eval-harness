from ppt_eval.domain import AuditEvent

_RECORD_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$")
_SHA256_PATTERN = re.compile(r"^[0-9a-f]{64}$")
_WRITABLE_REVIEW_VERDICTS = frozenset(
    {
        "CONFIRM_SYSTEM_DECISION",
        "OVERRIDE_DECISION",
        "REQUEST_MORE_EVIDENCE",
    }
)


def validated_record_id(value: object, *, label: str = "record id") -> str:
    text = str(value or "")
    if not _RECORD_ID_PATTERN.fullmatch(text):
        raise ValueError(f"{label} has an invalid format")
    return text


def validated_sha256(value: object) -> str:
    text = str(value or "")
    if not _SHA256_PATTERN.fullmatch(text):
        raise ValueError("sha256 must be 64 lowercase hexadecimal characters")
    return text


def to_primitive(value: Any) -> Any:
    """Convert domain objects into stable JSON-compatible values."""

    if dataclasses.is_dataclass(value):
        return {field.name: to_primitive(getattr(value, field.name)) for field in dataclasses.fields(value)}
    if isinstance(value, enum.Enum):
        return value.value
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, datetime):
        return value.astimezone(timezone.utc).isoformat()
    if isinstance(value, dict):
        return {str(key): to_primitive(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [to_primitive(item) for item in value]
    if hasattr(value, "model_dump"):
        return to_primitive(value.model_dump(mode="json"))
    return value


def stable_json(value: Any) -> str:
    return json.dumps(to_primitive(value), ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def sha256_file(path: str | Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


class LocalArtifactStore:
    """Content-addressed artifact store used by the single-node runtime."""

    def __init__(self, root: str | Path = "var/artifacts") -> None:
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        self._lock = threading.RLock()

    def put(
        self,
        source: str | Path,
        *,
        media_type: str = "application/octet-stream",
        original_name: str | None = None,
        expected_sha256: str | None = None,
    ) -> dict[str, Any]:
        """Atomically copy a file into the content-addressed store.

        ``expected_sha256`` closes the gap between streamed upload validation
        and durable storage.  The source is never moved or deleted here; its
        owner remains responsible for any quarantine/workspace cleanup.
        """

        source_path = Path(source)
        if not source_path.is_file():
            raise FileNotFoundError(source_path.name)
        digest = sha256_file(source_path)
        if expected_sha256 is not None and digest != validated_sha256(expected_sha256):
            raise ValueError("artifact content changed before durable storage")
        destination = self.root / digest[:2] / digest
        destination.parent.mkdir(parents=True, exist_ok=True)
        with self._lock:
            if destination.exists():
                if sha256_file(destination) != digest:
                    raise ValueError("content-addressed artifact failed integrity validation")
            else:
                temporary = destination.parent / f".{uuid.uuid4().hex}.tmp"
                try:
                    with source_path.open("rb") as source_stream, temporary.open(
                        "xb"
                    ) as destination_stream:
                        shutil.copyfileobj(source_stream, destination_stream, 1024 * 1024)
                        destination_stream.flush()
                        os.fsync(destination_stream.fileno())
                    if sha256_file(temporary) != digest:
                        raise ValueError("artifact copy failed integrity validation")
                    os.replace(temporary, destination)
                finally:
                    temporary.unlink(missing_ok=True)
        return {
            "sha256": digest,
            "uri": str(destination.resolve()),
            "size_bytes": source_path.stat().st_size,
            "media_type": media_type,
            "original_name": original_name or source_path.name,
        }

    def put_bytes(
        self,
        data: bytes,
        *,
        media_type: str = "application/octet-stream",
        original_name: str = "artifact.bin",
    ) -> dict[str, Any]:
        """Persist generated bytes directly without an unsafe temporary pathname."""

        digest = hashlib.sha256(data).hexdigest()
        destination = self.root / digest[:2] / digest
        destination.parent.mkdir(parents=True, exist_ok=True)
        with self._lock:
            if destination.exists():
                if sha256_file(destination) != digest:
                    raise ValueError("content-addressed artifact failed integrity validation")
            else:
                # Keep the atomic sibling name short.  Appending a UUID to the
                # 64-character digest can cross the legacy Windows MAX_PATH
                # boundary even when the final content-addressed path is valid.
                temporary = destination.parent / f".{uuid.uuid4().hex}.tmp"
                try:
                    temporary.write_bytes(data)
                    os.replace(temporary, destination)
                finally:
                    temporary.unlink(missing_ok=True)
        return {
            "sha256": digest,
            "uri": str(destination.resolve()),
            "size_bytes": len(data),
            "media_type": media_type,
            "original_name": original_name,
        }

    def resolve(self, sha256: str) -> Path:
        digest = validated_sha256(sha256)
        root = self.root.resolve()
        candidate = (self.root / digest[:2] / digest).resolve()
        if not candidate.is_relative_to(root):
            raise FileNotFoundError(digest)
        if not candidate.is_file():
            raise FileNotFoundError(digest)
        return candidate


class JsonRunRepository:
    """Atomic JSON report store used by the CLI and local API."""

    def __init__(self, root: str | Path = "var/runs") -> None:
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        self.review_path = self.root / "reviews.jsonl"
        self._lock = threading.RLock()

    def save(self, report: Any) -> Path:
        payload = to_primitive(report)
        run_id = validated_record_id(
            payload.get("run_id") or payload.get("id") or str(uuid.uuid4()),
            label="run_id",
        )
        target = self.root / f"{run_id}.json"
        temporary = target.with_suffix(f".json.{uuid.uuid4().hex}.tmp")
        with self._lock:
            temporary.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
            os.replace(temporary, target)
        return target

    def get(self, run_id: str) -> dict[str, Any]:
        safe_run_id = validated_record_id(run_id, label="run_id")
        root = self.root.resolve()
        path = (self.root / f"{safe_run_id}.json").resolve()
        if not path.is_relative_to(root):
            raise KeyError(safe_run_id)
        if not path.is_file():
            raise KeyError(safe_run_id)
        payload = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(payload, dict):
            raise ValueError("stored run report must be a JSON object")
        return {str(key): value for key, value in payload.items()}

    def list(self) -> list[dict[str, Any]]:
        reports = []
        for path in sorted(self.root.glob("*.json"), key=lambda item: item.stat().st_mtime, reverse=True):
            reports.append(json.loads(path.read_text(encoding="utf-8")))
        return reports

    def add_review(self, review: dict[str, Any]) -> dict[str, Any]:
        run_id = validated_record_id(review.get("run_id"), label="run_id")
        reviewer_id = str(review.get("reviewer_id") or "").strip()
        if not reviewer_id:
            raise ValueError("reviewer_id must be non-blank")
        verdict = str(review.get("verdict") or "").strip().upper()
        if verdict not in _WRITABLE_REVIEW_VERDICTS:
            raise ValueError("unsupported review verdict")
        review_id_value = review.get("review_id") or f"review-{uuid.uuid4().hex}"
        review_id = validated_record_id(review_id_value, label="review_id")
        client_request_id = str(review.get("client_request_id") or "").strip()
        fingerprint = hashlib.sha256(
            stable_json(
                {
                    key: value
                    for key, value in review.items()
                    if key not in {"review_id", "created_at", "idempotency_fingerprint"}
                }
            ).encode("utf-8")
        ).hexdigest()
        record = {
            **review,
            "review_id": review_id,
            "reviewer_id": reviewer_id,
            "verdict": verdict,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "run_id": run_id,
            "idempotency_fingerprint": fingerprint,
        }
        line = json.dumps(record, ensure_ascii=False, sort_keys=True)
        with self._lock:
            for existing in self._reviews_unlocked(run_id):
                same_request = (
                    client_request_id
                    and existing.get("client_request_id") == client_request_id
                )
                same_review_id = existing.get("review_id") == review_id
                if not same_request and not same_review_id:
                    continue
                if existing.get("idempotency_fingerprint") != fingerprint:
                    raise ValueError("review idempotency key was reused with different content")
                return existing
            with self.review_path.open("a", encoding="utf-8", newline="\n") as handle:
                handle.write(line + "\n")
                handle.flush()
                os.fsync(handle.fileno())
        return record

    def list_reviews(
        self, run_id: str | None = None
    ) -> builtins.list[dict[str, Any]]:
        safe_run_id = (
            validated_record_id(run_id, label="run_id") if run_id is not None else None
        )
        with self._lock:
            return self._reviews_unlocked(safe_run_id)

    def _reviews_unlocked(
        self, run_id: str | None
    ) -> builtins.list[dict[str, Any]]:
        if not self.review_path.is_file():
            return []
        reviews: builtins.list[dict[str, Any]] = []
        for line in self.review_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            payload = json.loads(line)
            if not isinstance(payload, dict):
                continue
            normalized = {str(key): value for key, value in payload.items()}
            if run_id is None or normalized.get("run_id") == run_id:
                reviews.append(normalized)
        reviews.sort(key=lambda item: str(item.get("created_at") or ""))
        return reviews


class JsonlAuditLog:
    """Append-only, hash-chained audit events."""

    def __init__(self, path: str | Path = "var/audit/events.jsonl") -> None:
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.RLock()

    def _last_hash(self) -> str | None:
        if not self.path.exists():
            return None
        last = ""
        with self.path.open("r", encoding="utf-8") as handle:
            for line in handle:
                if line.strip():
                    last = line
        if not last:
            return None
        payload = json.loads(last)
        if not isinstance(payload, dict):
            raise ValueError("audit event must be a JSON object")
        event_hash = payload.get("event_hash")
        if not isinstance(event_hash, str) or not event_hash:
            raise ValueError("audit event is missing event_hash")
        return event_hash

    def append(
        self,
        *,
        run_id: str,
        event_type: str,
        actor: str,
        payload: dict[str, Any] | Any,
        supersedes: str | None = None,
        occurred_at: str | None = None,
    ) -> AuditEvent:
        with self._lock:
            core = {
                "event_id": f"evt-{uuid.uuid4().hex}",
                "run_id": run_id,
                "event_type": event_type,
                "actor": actor,
                "occurred_at": occurred_at or datetime.now(timezone.utc).isoformat(),
                "payload": to_primitive(payload),
                "supersedes": supersedes,
                "previous_hash": self._last_hash(),
            }
            event_hash = hashlib.sha256(stable_json(core).encode("utf-8")).hexdigest()
            event = AuditEvent(**core, event_hash=event_hash)
            with self.path.open("a", encoding="utf-8", newline="\n") as handle:
                handle.write(json.dumps(to_primitive(event), ensure_ascii=False, sort_keys=True) + "\n")
                handle.flush()
                os.fsync(handle.fileno())
            return event

    def read(self) -> Iterable[dict[str, Any]]:
        if not self.path.exists():
            return []
        with self.path.open("r", encoding="utf-8") as handle:
            return [json.loads(line) for line in handle if line.strip()]

    def verify(self) -> tuple[bool, str | None]:
        previous: str | None = None
        for event in self.read():
            claimed = event.get("event_hash")
            candidate = dict(event)
            candidate.pop("event_hash", None)
            candidate.pop("schema_version", None)
            if candidate.get("previous_hash") != previous:
                return False, event.get("event_id")
            actual = hashlib.sha256(stable_json(candidate).encode("utf-8")).hexdigest()
            if actual != claimed:
                return False, event.get("event_id")
            previous = claimed
        return True, None


def git_sha(cwd: str | Path | None = None) -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=cwd, stderr=subprocess.DEVNULL, text=True
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "uncommitted"


_FONT_SUFFIXES = frozenset({".ttf", ".otf", ".ttc"})
_FONTCONFIG_FORMAT = "%{file}|%{family}|%{style}|%{fontversion}\n"


def font_fingerprint() -> str:
    """Return a stable digest for the fonts that can affect slide rendering.

    Docker/Linux uses fontconfig when available because its inventory reflects
    the fonts visible to LibreOffice.  Minimal images without ``fc-list`` fall
    back to content hashing well-known font directories.  ``"unavailable"`` is
    an explicit signal to the runtime that persistent render caches must not be
    reused across evaluations.
    """

    if os.name != "nt":
        fontconfig = shutil.which("fc-list")
        if fontconfig:
            fingerprint = _fontconfig_fingerprint(fontconfig)
            if fingerprint is not None:
                return fingerprint

    fingerprint = _font_directory_fingerprint(
        _font_search_roots(),
        hash_contents=os.name != "nt",
    )
    return fingerprint or "unavailable"


def _fontconfig_fingerprint(executable: str) -> str | None:
    environment = dict(os.environ)
    environment["LC_ALL"] = "C"
    environment["LANG"] = "C"
    try:
        completed = subprocess.run(
            [executable, f"--format={_FONTCONFIG_FORMAT}"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=10,
            env=environment,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if completed.returncode != 0 or not isinstance(completed.stdout, str):
        return None
    inventory = sorted(
        {
            line.strip()
            for line in completed.stdout.splitlines()
            if line.strip()
        }
    )
    if not inventory:
        return None
    return hashlib.sha256("\n".join(inventory).encode("utf-8")).hexdigest()


def _font_search_roots() -> tuple[Path, ...]:
    if os.name == "nt":
        return (Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts",)

    roots = [Path("/usr/share/fonts"), Path("/usr/local/share/fonts")]
    xdg_data_home = str(os.environ.get("XDG_DATA_HOME") or "").strip()
    if xdg_data_home:
        roots.append(Path(xdg_data_home) / "fonts")
    try:
        user_root = Path.home()
    except (OSError, RuntimeError):
        pass
    else:
        roots.extend((user_root / ".local/share/fonts", user_root / ".fonts"))
    return tuple(roots)


def _font_directory_fingerprint(
    roots: Iterable[Path],
    *,
    hash_contents: bool,
) -> str | None:
    inventory: list[str] = []
    for root_index, root in enumerate(roots):
        try:
            if not root.is_dir():
                continue
            candidates = sorted(
                (
                    path
                    for path in root.rglob("*")
                    if path.suffix.casefold() in _FONT_SUFFIXES
                ),
                key=lambda path: path.as_posix().casefold(),
            )
        except OSError:
            continue
        for path in candidates:
            try:
                if not path.is_file():
                    continue
                relative = path.relative_to(root).as_posix()
                stat = path.stat()
                identity = (
                    sha256_file(path)
                    if hash_contents
                    else str(stat.st_mtime_ns)
                )
            except (OSError, ValueError):
                continue
            inventory.append(f"{root_index}|{relative}|{stat.st_size}|{identity}")
    if not inventory:
        return None
    return hashlib.sha256("\n".join(inventory).encode("utf-8")).hexdigest()
